'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { _electron: electron } = require('playwright');
(async () => {
  const root = path.resolve(__dirname, '..');
  let app;
  try {
    app = await electron.launch({ executablePath: require('electron'), args: [root], cwd: root, env: { ...process.env, YAN_E2E_MODE: '1', YAN_E2E_USER_DATA_DIR: fs.mkdtempSync(path.join(os.tmpdir(), 'yan-browser-acceptance-')) } });
    const page = await app.firstWindow();
    await page.waitForFunction(() => window.__YAN_APP_READY__ === true);
    const result = await page.evaluate(() => {
      if (!state.currentSession) newSession();
      setEmptyState(false); showMainPage('chat');
      const el = appendMessage('assistant', '');
      const body = el.querySelector('.msg-body');
      const call = (id, purpose) => ({ type: 'tool_call', stage: 'work', callId: id, name: 'yan_browser_browser_snapshot', args: { purpose, acceptance: { target: 'preview', check: 'responsive navigation' } } });
      const timeline = [call('a', 'frontend_acceptance')];
      const run = { runId: 'acceptance-ui', status: 'working', timeline };
      renderAgentRunBody(body, run, '');
      const first = body.querySelector('.browser-acceptance-timeline-group');
      if (!first) throw new Error('Missing acceptance group');
      first.open = true;
      const thinking = { type: 'thinking', stage: 'work', content: '正在检查窄屏布局', streaming: true, openCodeKey: 'acceptance-stream-thinking' };
      timeline.push(thinking);
      renderAgentRunBody(body, run, '');
      const thinkingNode = body.querySelector('[data-agent-part-key="acceptance-stream-thinking"]');
      if (!thinkingNode || !first.contains(thinkingNode)) throw new Error('Streaming thinking appeared outside acceptance');
      thinking.content += '，检查导航按钮';
      renderAgentRunBody(body, run, '');
      if (body.querySelector('[data-agent-part-key="acceptance-stream-thinking"]') !== thinkingNode) throw new Error('Thinking node replaced during streaming');
      thinking.streaming = false;
      timeline.push({ type: 'tool_result', callId: 'a', name: 'yan_browser_browser_snapshot', ok: true, output: '{}' }, call('b', 'frontend_acceptance'), call('c', 'website_operation'));
      renderAgentRunBody(body, run, '');
      const updated = body.querySelector('.browser-acceptance-timeline-group');
      if (!updated.contains(thinkingNode) || body.querySelector('[data-agent-part-key="acceptance-stream-thinking"]') !== thinkingNode) throw new Error('Thinking moved after tool arrived');
      const toolNode = updated.querySelector('[data-call-id="b"]');
      if (!toolNode) throw new Error('Running acceptance tool appeared outside container');
      timeline.push({ type: 'tool_result', callId: 'b', name: 'yan_browser_browser_snapshot', ok: true, output: '{}' });
      renderAgentRunBody(body, run, '');
      if (updated.querySelector('[data-call-id="b"]') !== toolNode) throw new Error('Tool moved on completion');
      const ordinary = body.querySelector('[data-call-id="c"]');
      const info = { count: body.querySelectorAll('.browser-acceptance-timeline-group').length, same: first === updated, open: updated.open, label: updated.querySelector('summary').textContent, calls: updated.querySelectorAll('[data-call-id]').length, ordinaryOutside: !!ordinary && !updated.contains(ordinary) };
      run.status = 'done';
      renderAgentRunBody(body, run, '');
      for (const details of body.querySelectorAll('details')) details.open = !details.classList.contains('browser-acceptance-timeline-group');
      return info;
    });
    assert.equal(result.count, 1);
    assert.equal(result.same, true);
    assert.equal(result.open, true);
    assert.match(result.label, /Yan Agent 正在调用内置浏览器进行前端验收/);
    assert.equal(result.ordinaryOutside, true);
    const evidence = path.join(root, '.yanagent', 'evidence'); fs.mkdirSync(evidence, { recursive: true });
    await page.screenshot({ path: path.join(evidence, 'browser-acceptance.png') });
    console.log(JSON.stringify(result));
  } finally { await app?.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
