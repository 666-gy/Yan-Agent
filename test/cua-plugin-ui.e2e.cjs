'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { _electron: electron } = require('playwright');
const root = path.resolve(__dirname, '..');
const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'yan-computer-ui-'));
(async () => {
  let app;
  try {
    app = await electron.launch({ executablePath: require('electron'), args: [root], cwd: root,
      env: { ...process.env, YAN_E2E_MODE: '1', YAN_E2E_USER_DATA_DIR: userData } });
    const page = await app.firstWindow();
    await page.waitForFunction(() => window.__YAN_APP_READY__ && window.YanComposerPlugins);
    const catalog = await page.evaluate(() => window.yan.pluginsCatalog());
    const plugin = catalog.plugins.find(item => item.id === 'yan-computer-use');
    assert.equal(plugin.name, 'Yan Computer Use');
    assert.equal(plugin.installation.enabled, true);
    assert.equal(plugin.installation.ready, true);
    const mcp = await page.evaluate(() => window.yan.mcpList());
    assert.ok(!JSON.stringify(mcp).includes('yan_computer'), 'Former standalone MCP is absent');
    await page.locator('#attachBtn').click();
    const choice = page.locator('[data-composer-plugin-choice="yan-computer-use"]');
    await choice.waitFor();
    assert.equal(await choice.locator('.skill-call-name').innerText(), 'Yan Computer Use');
    const evidence = path.join(root, 'output/playwright/computer-use');
    fs.mkdirSync(evidence, { recursive: true });
    await page.locator('#attachmentMenu').evaluate(node => node.getAnimations().forEach(animation => animation.finish()));
    await page.locator('#attachmentMenu').screenshot({ path: path.join(evidence, 'plugin-menu.png') });
    await choice.click();
    const token = page.locator('#composerInput [data-composer-plugin-id="yan-computer-use"]');
    await token.waitFor();
    assert.ok((await token.innerText()).includes('Yan Computer Use'));
    assert.equal(await page.evaluate(() => window.YanComposerPlugins.validate()), true);
    await page.locator('#composer').screenshot({ path: path.join(evidence, 'plugin-selected.png') });
    await page.locator('[data-nav="plugins"]').click();
    const card = page.locator('[aria-labelledby="plugin-group-productivity"] [data-plugin-open="yan-computer-use"]');
    await card.waitFor();
    assert.ok((await card.innerText()).includes('Yan Computer Use'));
    await page.locator('#pagePluginPackages').screenshot({ path: path.join(evidence, 'plugin-page.png') });
    await card.click();
    await page.locator('#pluginDetailTitle').waitFor();
    assert.equal(await page.locator('#pluginDetailTitle').innerText(), 'Yan Computer Use');
    assert.equal(await page.locator('.plugin-example-prompt').count(), 3);
    assert.match(await page.locator('.plugin-example-prompt').first().innerText(), /播放一个歌单/);
    assert.match(await page.locator('.plugin-detail-description').innerText(), /^Yan Computer Use lets Yan Agent/);
    assert.equal(await page.locator('#pluginSkillList [data-skill-id="computer-use"]').count(), 1);
    assert.equal(await page.locator('#pluginSkillsTitle span').innerText(), '1');
    const toggle = page.locator('[data-plugin-action="toggle"]');
    assert.equal(await toggle.isChecked(), true);
    await toggle.click();
    await page.waitForFunction(() => document.getElementById('pluginDetailState').textContent === '已关闭');
    assert.equal(await toggle.isChecked(), false);
    await toggle.click();
    await page.waitForFunction(() => document.getElementById('pluginDetailState').textContent === '已启用');
    const skillToggle = page.locator('#pluginSkillList [data-skill-id="computer-use"]');
    await skillToggle.uncheck();
    await page.waitForFunction(() => document.querySelector('[data-skill-id="computer-use"]').getAttribute('aria-busy') === 'false');
    await page.locator('#pluginsSkillsTab').click();
    const skillCard = page.locator('#skillMarketGrid [data-market-id="yan-computer-use"]');
    await skillCard.waitFor();
    await skillCard.click();
    const sharedToggle = page.locator('[data-skill-toggle="yan-computer-use"]');
    await sharedToggle.waitFor();
    assert.equal(await sharedToggle.isChecked(), false);
    await sharedToggle.check();
    await page.waitForFunction(() => !document.querySelector('[data-skill-toggle="yan-computer-use"]').disabled);
    await page.locator('#pageSkills').screenshot({ path: path.join(evidence, 'computer-skill.png') });
    await page.locator('#pluginsPackagesTab').click();
    await page.locator('#pluginDetailTitle').waitFor();
    await page.waitForFunction(() => document.querySelector('#pluginSkillList [data-skill-id="computer-use"]').checked);
    await page.evaluate(() => applyTheme('light'));
    await page.evaluate(() => document.getElementById('pluginDetailContent').scrollIntoView({ block: 'start' }));
    await page.locator('#pagePluginPackages').screenshot({ path: path.join(evidence, 'plugin-detail.png') });
    await page.locator('.plugin-example-send').first().click();
    await page.waitForFunction(() => document.querySelector('#composerInput [data-composer-plugin-id="yan-computer-use"]'));
    assert.equal(await page.evaluate(() => getComposerText()), '播放一个歌单，帮我进入专注状态。');
    console.log('PASS: Chinese examples, English introduction, shared Computer Use skill in both pages, synchronized switches and safe example draft.');
  } finally {
    await app?.close().catch(() => {});
    assert.equal(path.dirname(userData), path.resolve(os.tmpdir()));
    await fs.promises.rm(userData, { recursive: true, force: true, maxRetries: 10, retryDelay: 250 });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
