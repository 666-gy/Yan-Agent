const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const { _electron } = require('playwright');
const root = path.resolve(__dirname, '..');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'yan-downloads-'));
const defaultDir = path.join(profile, 'system-downloads'), customDir = path.join(profile, 'custom');
const shots = path.join(root, 'output/playwright/browser-downloads');
fs.mkdirSync(shots, { recursive: true });
fs.mkdirSync(defaultDir, { recursive: true });
(async () => {
 const server = http.createServer((req,res) => { res.writeHead(200, {'Content-Type':'application/octet-stream', 'Content-Disposition':'attachment; filename="sample.txt"'}); res.end('real browser download'); });
 await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
 const url = `http://127.0.0.1:${server.address().port}/download`;
 const app = await _electron.launch({ executablePath: require('electron'), args:[root], cwd:root, env:{...process.env,YAN_E2E_MODE:'1',YAN_E2E_USER_DATA_DIR:profile} });
 try {
  await app.evaluate(({app,dialog}, {defaultDir,customDir}) => {
   app.setPath('downloads',defaultDir);
   global.downloadDialogs=[]; global.saveResult=null;
   dialog.showOpenDialog=async()=>({canceled:false,filePaths:[customDir]});
   dialog.showSaveDialogSync=(_window,options)=>{global.downloadDialogs.push(options);return global.saveResult;};
  }, {defaultDir,customDir});
  const page=await app.firstWindow(); await page.waitForFunction(()=>window.__YAN_APP_READY__);
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#settingsBtn').click(); await page.locator('#settings-tab-browser').click();
  assert.equal(await page.locator('#browserDownloadLocation').textContent(),'系统下载文件夹');
  assert.equal(await page.evaluate(()=>window.yan.browserDownloadLocation()),defaultDir);
  await page.locator('#browserDownloadsManage').click();
  await page.locator('.browser-download-empty').waitFor();
  await page.evaluate(()=>applyTheme('light')); await page.screenshot({path:path.join(shots,'empty.png')});
  await page.locator('#browserDownloadsClose').click();
  const download=async()=>app.evaluate(({session},url)=>session.fromPartition('persist:yan-browser').downloadURL(url),url);
  const waitForDownloads=async predicate=>{ for(let i=0;i<200;i++){ const items=await page.evaluate(()=>window.yan.browserDownloads()); if(predicate(items))return; await new Promise(r=>setTimeout(r,50)); } throw new Error('Download timed out'); };
  const waitCompleted= count=>waitForDownloads(items=>items.filter(x=>x.status==='completed' && x.exists).length===count);
  await download(); await waitCompleted(1);
  assert.equal(fs.readFileSync(path.join(defaultDir,'sample.txt'),'utf8'),'real browser download');
  assert.equal(await app.evaluate(()=>global.downloadDialogs.length),0);
  await page.locator('#browserDownloadChange').click();
  await page.waitForFunction(()=>state.config.browser.downloadDirectory.endsWith('custom'));
  await download(); await waitCompleted(2);
  await download(); await waitCompleted(3);
  assert.ok(fs.existsSync(path.join(customDir,'sample.txt'))); assert.ok(fs.existsSync(path.join(customDir,'sample (1).txt')));
  await page.locator('#browserAskDownload').check(); await page.waitForFunction(()=>state.config.browser.askDownloadLocation===true);
  const chosen=path.join(profile,'chosen.txt');
  await app.evaluate((_electron,p)=>{global.saveResult=p;},chosen);
  await download(); await waitCompleted(4); assert.equal(fs.readFileSync(chosen,'utf8'),'real browser download');
  assert.equal(await app.evaluate(()=>global.downloadDialogs.length),1);
  assert.equal(await app.evaluate(()=>global.downloadDialogs[0].defaultPath),path.join(customDir,'sample.txt'));
  await app.evaluate(()=>{global.saveResult=undefined;});
  await download(); await waitForDownloads(items=>items.some(x=>x.status==='cancelled'));
  assert.equal(await app.evaluate(()=>global.downloadDialogs.length),2);
  await page.reload(); await page.waitForFunction(()=>window.__YAN_APP_READY__);
  await page.locator('#settingsBtn').click(); await page.locator('#settings-tab-browser').click();
  assert.equal(await page.locator('#browserAskDownload').isChecked(),true);
  assert.equal(await page.locator('#browserDownloadLocation').textContent(),customDir);
  await page.locator('#browserDownloadsManage').click(); await page.locator('.browser-download-row').first().waitFor();
  assert.equal(await page.locator('.browser-download-row').count(),5);
  await page.locator('#browserDownloadsSearch').fill('chosen'); assert.equal(await page.locator('.browser-download-row').count(),1);
  await page.locator('#browserDownloadsSearch').fill('');
  await page.evaluate(()=>applyTheme('light')); await page.screenshot({path:path.join(shots,'records.png')});
  await page.locator('#browserDownloadsClear').click(); await page.locator('.browser-download-empty').waitFor();
  assert.ok(fs.existsSync(chosen)); assert.ok(fs.existsSync(path.join(customDir,'sample.txt')));
  await page.setViewportSize({width:375,height:900}); await page.screenshot({path:path.join(shots,'narrow.png')});
  console.log('Downloads passed: system default, folder picker, custom location, collision handling, save-dialog acceptance/cancellation, persisted preferences, search and history-only clearing. Native dialog responses stubbed; actual HTTP downloads and files verified.');
 } finally {await app.close();server.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
