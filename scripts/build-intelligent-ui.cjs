'use strict';
const esbuild=require('esbuild'), fs=require('node:fs'), path=require('node:path');
const root=path.resolve(__dirname,'..');
async function build(){
  // The server consumes plain schema/prompt data, never React or UI dependencies.
  const library=require('../lib/intelligent-ui/catalog.cjs').makeCatalog();
  const prompt=require('../lib/intelligent-ui/prompt-options.cjs').buildPrompt(library);
  fs.writeFileSync(path.join(root,'lib/intelligent-ui/catalog.generated.json'),JSON.stringify({root:library.root,components:Object.keys(library.components),schema:library.toJSONSchema(),prompt},null,2)+'\n');
  const result=await esbuild.build({entryPoints:[path.join(root,'renderer/intelligent-ui-openui.jsx')],outdir:'openui-build',bundle:true,write:false,minify:true,metafile:true,alias:{'@openuidev/react-lang':require.resolve('@openuidev/react-lang').replace(/\.cjs$/,'.mjs'),'@openuidev/react-ui/genui-lib':require.resolve('@openuidev/react-ui/genui-lib').replace(/\.cjs$/,'.mjs')},platform:'browser',format:'iife',target:'chrome130',define:{'process.env.NODE_ENV':'"production"'},legalComments:'inline',loader:{'.woff2':'dataurl','.woff':'dataurl','.ttf':'dataurl'}});
  const js=result.outputFiles.find(file=>file.path.endsWith('.js'));
  const css=result.outputFiles.find(file=>file.path.endsWith('.css'));
  const destination=path.join(root,'renderer/vendor/openui');fs.mkdirSync(destination,{recursive:true});
  fs.writeFileSync(path.join(destination,'intelligent-ui-runtime.js'),'/* Generated locally; executed only inside the panel sandbox. */\nwindow.YanIntelligentUiOpenUiSource='+JSON.stringify(js.text)+';\nwindow.YanIntelligentUiOpenUiCss='+JSON.stringify(css?.text || '')+';\n');
  await esbuild.build({entryPoints:[path.join(root,'renderer/intelligent-ui/panel.js')],outfile:path.join(root,'renderer/intelligent-ui.js'),bundle:true,platform:'browser',format:'iife',target:'chrome130',banner:{js:'/* Generated by bundle:intelligent-ui; edit renderer/intelligent-ui/ sources. */'}});
  const template=fs.readFileSync(path.join(root,'renderer/intelligent-ui/sandbox.html'),'utf8');
  const sandbox=fs.readFileSync(path.join(root,'renderer/intelligent-ui/sandbox.js'),'utf8');
  fs.writeFileSync(path.join(root,'renderer/intelligent-ui-host.html'),template.replace('{{SANDBOX_SOURCE}}',()=>sandbox));
  fs.copyFileSync(path.join(root,'lib/intelligent-ui/i18n.cjs'),path.join(destination,'intelligent-ui-i18n.js'));
  // Include notices for every bundled package, including transitive chart/control dependencies.
  const packageDirs=new Set();
  for(const input of Object.keys(result.metafile.inputs)){
    if(!input.includes('node_modules'))continue;
    let dir=path.dirname(path.resolve(root,input));
    while(dir!==path.dirname(dir)){
      if(fs.existsSync(path.join(dir,'package.json')) && JSON.parse(fs.readFileSync(path.join(dir,'package.json'),'utf8')).name){packageDirs.add(dir);break;}
      dir=path.dirname(dir);
    }
  }
  const notices=[...packageDirs].sort().map(dir=>{
    const pkg=JSON.parse(fs.readFileSync(path.join(dir,'package.json'),'utf8'));
    const license=fs.readdirSync(dir).find(file=>/^licen[sc]e(?:[.-].*)?$/i.test(file) && fs.statSync(path.join(dir,file)).isFile());
    return pkg.name+'@'+pkg.version+' ('+(pkg.license || 'see package')+')\n\n'+(license?fs.readFileSync(path.join(dir,license),'utf8'):'License notice in package metadata: '+JSON.stringify(pkg.license));
  });
  fs.writeFileSync(path.join(destination,'LICENSES.txt'),notices.join('\n\n--------------------\n\n'));
  console.log('Built OpenUI: '+js.contents.length+' JS bytes, '+(css?.contents.length || 0)+' CSS bytes; '+packageDirs.size+' package notices.');
}
build().catch(error=>{console.error(error);process.exitCode=1;});
