"""Subset Noto Serif SC for the public site.

The bundled variable font is ~25 MB, far too heavy for a web page. This keeps
the wght axis (400-700), every character used by the site, and the 3,755
GB2312 level-1 characters so new guide text rarely falls back to system fonts.

Run after changing site copy:  python scripts/build-site-font.py
Requires: fontTools, brotli
"""
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

root = Path(__file__).resolve().parent.parent
docs = root / "docs"
source = docs / "assets" / "NotoSerifSC.ttf"

cjk = lambda text: {c for c in text if ord(c) >= 0x2000}  # Latin comes from Source Serif 4

site = set()
for path in [docs / "index.html", *docs.glob("site*.js")]:
    site |= cjk(path.read_text(encoding="utf-8"))
site |= cjk("“”‘’…—·")
common = set()
# GB2312 level 1: rows 0xB0-0xD7, cells 0xA1-0xFE (row 0xD7 ends at 0xF9).
for row in range(0xB0, 0xD8):
    for cell in range(0xA1, 0xFA if row == 0xD7 else 0xFF):
        common.add(bytes([row, cell]).decode("gb2312"))
common |= {chr(c) for c in range(0x3000, 0x3040)} | {chr(c) for c in range(0xFF01, 0xFF5F)}
common -= site


def build(chars, name):
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    options.drop_tables += ["vhea", "vmtx", "VVAR", "VORG"]  # horizontal text only
    font = TTFont(source)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[ord(c) for c in chars])
    subsetter.subset(font)
    font = instancer.instantiateVariableFont(font, {"wght": (400, 700)})
    font.flavor = "woff2"
    target = out / f"{name}.woff2"
    font.save(target)
    print(f"{target.relative_to(root)}: {len(chars)} chars, {target.stat().st_size // 1024} KB")


def ranges(chars):
    points, spans = sorted(ord(c) for c in chars), []
    for p in points:
        if spans and p == spans[-1][1] + 1:
            spans[-1][1] = p
        else:
            spans.append([p, p])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in spans)


out = docs / "assets" / "fonts"
out.mkdir(parents=True, exist_ok=True)
build(site, "noto-serif-sc-site")
build(common, "noto-serif-sc-common")
# Browsers fetch the second file only when a page uses a character outside the site set.
faces = "".join(
    f'@font-face {{ font-family: "Noto Serif SC Site"; src: url("assets/fonts/{name}.woff2") format("woff2"); '
    f"font-weight: 400 700; font-display: swap; unicode-range: {ranges(chars)}; }}\n"
    for name, chars in [("noto-serif-sc-site", site), ("noto-serif-sc-common", common)]
)
(docs / "site-fonts.css").write_text(
    "/* Generated by scripts/build-site-font.py. Do not edit manually. */\n" + faces, encoding="utf-8"
)
