"use strict";
// Keep the public site's version and release notes aligned with the desktop app.
// Run: node scripts/sync-site-content.cjs
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const context = { window: {} };
vm.runInNewContext(
  fs.readFileSync(path.join(root, "renderer/release-notes.js"), "utf8"),
  context,
  { timeout: 1000 },
);
const notes = context.window.YanReleaseNotes;
if (!notes || !Array.isArray(notes.pages) || !notes.pages.length)
  throw new Error("Invalid release notes");
const version = JSON.parse(
  fs.readFileSync(path.join(root, "package.json"), "utf8"),
).version;
let output = {
  version,
  label: version,
  ...notes,
};
// Website editorial release source; keep public notes separate from the app changelog.
const siteNotesPath = path.join(root, `docs/releases/v${version}.md`);
if (fs.existsSync(siteNotesPath)) {
  const pages = [];
  let current;
  for (const line of fs.readFileSync(siteNotesPath, "utf8").split(/\r?\n/)) {
    const heading = /^(#{1,3})\s+(.+)$/.exec(line);
    if (heading) {
      current = { title: heading[2], paragraphs: [], bullets: [] };
      pages.push(current);
    } else if (line.startsWith("- ") && current) current.bullets.push(line.slice(2));
    else if (line.trim() && current) current.paragraphs.push(line.trim());
  }
  output = { ...output, pages };
}
const serialized = JSON.stringify(output, null, 2).replace(/</g, "\\u003c");
fs.writeFileSync(
  path.join(root, "docs/site-release.js"),
  "// Generated by scripts/sync-site-content.cjs. Do not edit manually.\nwindow.YanSiteRelease = " +
    serialized +
    ";\n",
);
console.log("Website release content synchronized: " + version);

// Screenshot slots: every <id>.webp/.png/.jpg in docs/assets/shots fills the slot with that id.
const shotsDir = path.join(root, "docs/assets/shots");
const shots = {};
for (const file of fs.existsSync(shotsDir) ? fs.readdirSync(shotsDir).sort() : []) {
  const match = /^([a-z0-9-]+)\.(webp|png|jpe?g)$/i.exec(file);
  if (match && !shots[match[1]]) shots[match[1]] = `assets/shots/${file}`;
}
fs.writeFileSync(
  path.join(root, "docs/site-shots.js"),
  "// Generated by scripts/sync-site-content.cjs. Do not edit manually.\nwindow.YanSiteShots = " +
    JSON.stringify(shots, null, 2) +
    ";\n",
);
console.log("Website screenshots synchronized: " + Object.keys(shots).length);
